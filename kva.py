def _cat1_winner_knowledge(ctx: KVAContext) -> CategoryResult:
    """Category 1 — What IIOS knows about winners."""
    cat = CategoryResult(1, "Winner Knowledge")
    _section("CATEGORY 1 — WINNER KNOWLEDGE")

    winner_dna = ctx.winner_dna

    # Q1: What characteristics consistently precede winners?
    conditions_all: Dict[str, List[float]] = defaultdict(list)
    for f in winner_dna:
        raw = getattr(f, "raw", None) or {}
        conf = _safe_float(raw.get("test_confidence", 0))
        for cond in raw.get("conditions", []):
            feat_name = cond.split(" ")[0] if cond else ""
            if feat_name:
                conditions_all[feat_name].append(conf)

    top_features = sorted(
        ((k, sum(v) / len(v), len(v)) for k, v in conditions_all.items()),
        key=lambda x: x[1], reverse=True,
    )[:10]

    if top_features:
        top_str = ", ".join(f"{n}(conf={c:.2f},cnt={cnt})"
                            for n, c, cnt in top_features[:5])
        answer_q1 = f"{len(conditions_all)} distinct features found in winner conditions. Top: {top_str}"
        conf_q1 = min(1.0, sum(c for _, c, _ in top_features[:5]) / max(len(top_features[:5]), 1))
    else:
        answer_q1 = "No winner DNA conditions available yet — learning in progress."
        conf_q1 = 0.1

    a1 = KnowledgeAnswer(
        question="What characteristics consistently precede winners?",
        answer=answer_q1,
        evidence=[f"{len(winner_dna)} winner DNA records from study002a"],
        supporting_studies=["study002a"],
        supporting_years=["2021-2025"],
        supporting_regimes=[],
        confidence=conf_q1,
        knowledge_source="KnowledgeProvider / study002a",
        knowledge_confidence=conf_q1 * 80,
        evidence_strength=min(100, len(winner_dna) * 10),
        cross_year=75.0 if conf_q1 > 0.3 else 20.0,
        cross_regime=50.0,
        explainability=90.0 if top_features else 20.0,
        completeness=60.0 if len(winner_dna) >= 5 else 30.0,
        novelty=60.0,
        consistency=70.0 if conf_q1 > 0.5 else 40.0,
    )
    cat.questions.append(a1)
    _q(a1.question, a1.answer, a1.confidence)

    # Q2: Which characteristics became stronger over time?
    # Edges are ordered by creation date; compare composite scores
    edges_with_score = [(e.edge_id, e.composite_score, str(e.created_at)[:10])
                         for e in ctx.edges
                         if hasattr(e, "composite_score") and e.composite_score > 0]
    edges_with_score.sort(key=lambda x: x[2])  # by creation date
    if len(edges_with_score) > 5:
        early = [s for _, s, _ in edges_with_score[:len(edges_with_score)//2]]
        late  = [s for _, s, _ in edges_with_score[len(edges_with_score)//2:]]
        early_avg = sum(early) / len(early)
        late_avg  = sum(late)  / len(late)
        trend = "IMPROVING" if late_avg > early_avg else "STABLE/DECLINING"
        answer_q2 = (f"Edge composite score trend: early_avg={early_avg:.3f} → "
                     f"late_avg={late_avg:.3f} → {trend}. "
                     f"{len(edges_with_score)} edges analysed across time.")
        conf_q2 = 0.70
    else:
        answer_q2 = f"Insufficient edge history for time-series analysis ({len(edges_with_score)} edges)."
        conf_q2 = 0.30

    a2 = KnowledgeAnswer(
        question="Which characteristics became stronger over time?",
        answer=answer_q2,
        evidence=[f"{len(ctx.edges)} edges analysed"],
        supporting_studies=["study002", "re001a"],
        confidence=conf_q2,
        knowledge_source="KnowledgeProvider / edges",
        knowledge_confidence=conf_q2 * 80,
        evidence_strength=min(100, len(ctx.edges) / 3),
        cross_year=60.0, cross_regime=50.0,
        explainability=80.0, completeness=60.0,
        novelty=55.0, consistency=65.0,
    )
    cat.questions.append(a2)
    _q(a2.question, a2.answer, a2.confidence)

    # Q3: Which winner DNA has highest confidence?
    dna_confs = []
    for f in winner_dna:
        raw = getattr(f, "raw", None) or {}
        tc = _safe_float(raw.get("test_confidence", 0))
        lift = _safe_float(raw.get("test_lift", 0))
        conds = raw.get("conditions", [])
        n_match = _safe_float(raw.get("test_n_match", 0))
        dna_confs.append((tc, lift, n_match, ", ".join(conds[:2]) if conds else "N/A"))

    dna_confs.sort(key=lambda x: x[0], reverse=True)

    if dna_confs:
        best = dna_confs[0]
        answer_q3 = (f"Highest confidence winner DNA: conf={best[0]:.4f} "
                     f"lift={best[1]:.2f} n_match={best[2]:.0f} "
                     f"conditions=[{best[3][:80]}]")
        conf_q3 = best[0]
    else:
        answer_q3 = "No winner DNA confidence data available."
        conf_q3 = 0.0

    a3 = KnowledgeAnswer(
        question="Which winner DNA has highest confidence?",
        answer=answer_q3,
        evidence=[f"Best confidence: {dna_confs[0][0]:.4f}" if dna_confs else "none"],
        supporting_studies=["study002a"],
        supporting_years=["2021-2025"],
        confidence=conf_q3,
        knowledge_source="KnowledgeProvider / WINNER_DNA findings",
        knowledge_confidence=conf_q3 * 100,
        evidence_strength=min(100, len(winner_dna) * 12),
        cross_year=70.0, cross_regime=55.0,
        explainability=95.0, completeness=65.0,
        novelty=50.0, consistency=75.0,
    )
    cat.questions.append(a3)
    _q(a3.question, a3.answer, a3.confidence)

    # Score category
    scores = [a.overall_score for a in cat.questions]
    cat.score = sum(scores) / len(scores) if scores else 0.0
    cat.status = _score_to_status(cat.score)

    if len(winner_dna) < 10:
        cat.gaps.append(f"Only {len(winner_dna)} winner DNA records — more study cycles needed")
    if not any(a.confidence > 0.7 for a in cat.questions):
        cat.gaps.append("No winner DNA with confidence > 0.70 yet")
    cat.observations.append(f"{len(conditions_all)} distinct features appear in winner conditions")
    cat.observations.append(f"Study002a covered {280909} observations over 2021-2025")
    if top_features:
        cat.observations.append(f"Top predictive feature: {top_features[0][0]} (conf={top_features[0][1]:.2f})")
    return cat


def _cat2_loser_knowledge(ctx: KVAContext) -> CategoryResult:
    """Category 2 — What IIOS knows about losers."""
    cat = CategoryResult(2, "Loser Knowledge")
    _section("CATEGORY 2 — LOSER KNOWLEDGE")

    loser_dna = ctx.loser_dna

    # Q1: Why do stocks underperform?
    loser_conds: Dict[str, int] = Counter()
    for f in loser_dna:
        raw = getattr(f, "raw", None) or {}
        for cond in raw.get("conditions", []):
            feat = cond.split(" ")[0] if cond else ""
            if feat:
                loser_conds[feat] += 1

    if loser_conds:
        top = sorted(loser_conds.items(), key=lambda x: x[1], reverse=True)[:5]
        answer = f"Loser conditions identified: {', '.join(f'{k}(n={v})' for k,v in top)}"
        conf = 0.55
    else:
        answer = "Loser DNA conditions not yet available — 1 loser finding recorded but conditions unpopulated."
        conf = 0.15

    a1 = KnowledgeAnswer(
        question="Why do stocks underperform?",
        answer=answer,
        evidence=[f"{len(loser_dna)} loser DNA records"],
        supporting_studies=["study002a"],
        confidence=conf,
        knowledge_source="KnowledgeProvider / LOSER_DNA findings",
        knowledge_confidence=conf * 80, evidence_strength=max(10, len(loser_dna)*15),
        cross_year=30.0, cross_regime=25.0,
        explainability=50.0, completeness=20.0, novelty=40.0, consistency=40.0,
    )
    cat.questions.append(a1)
    _q(a1.question, a1.answer, a1.confidence)

    # Q2: What DNA consistently predicts failure?
    # Edges with low win rates and negative returns
    failing_edges = [e for e in ctx.edges
                     if hasattr(e, "oos_win_rate") and e.oos_win_rate < 0.40]
    if failing_edges:
        worst = sorted(failing_edges, key=lambda e: e.oos_win_rate)[:3]
        answer2 = (f"{len(failing_edges)} edges show OOS win rate < 40%. "
                   f"Worst: {worst[0].description[:80] if hasattr(worst[0],'description') else worst[0].edge_id}")
        conf2 = 0.65
    else:
        answer2 = f"No edges with OOS win rate < 40% found in {len(ctx.edges)} edges."
        conf2 = 0.50

    a2 = KnowledgeAnswer(
        question="What DNA consistently predicts failure?",
        answer=answer2,
        evidence=[f"{len(failing_edges)} failing edges identified"],
        supporting_studies=["re001a", "study002"],
        confidence=conf2,
        knowledge_source="KnowledgeProvider / edges (low win rate)",
        knowledge_confidence=conf2 * 80, evidence_strength=min(80, len(failing_edges)*10),
        cross_year=45.0, cross_regime=40.0,
        explainability=70.0, completeness=35.0, novelty=50.0, consistency=55.0,
    )
    cat.questions.append(a2)
    _q(a2.question, a2.answer, a2.confidence)

    # Q3: Which loser DNA survived all years?
    answer3 = (f"Loser DNA corpus is small ({len(loser_dna)} records). "
               f"Cross-year loser validation requires additional HKAP cycles. "
               f"Current finding: 1 loser DNA recorded from study002a (2021-2025).")
    a3 = KnowledgeAnswer(
        question="Which loser DNA survived all years?",
        answer=answer3,
        evidence=["1 loser DNA finding from study002a"],
        supporting_studies=["study002a"],
        supporting_years=["2021-2025"],
        confidence=0.20,
        knowledge_source="KnowledgeProvider",
        knowledge_confidence=20.0, evidence_strength=15.0,
        cross_year=20.0, cross_regime=15.0,
        explainability=60.0, completeness=15.0, novelty=35.0, consistency=30.0,
    )
    cat.questions.append(a3)
    _q(a3.question, a3.answer, a3.confidence)

    scores = [a.overall_score for a in cat.questions]
    cat.score = sum(scores) / len(scores) if scores else 0.0
    cat.status = _score_to_status(cat.score)
    cat.gaps.append("Loser DNA corpus critically small (1 record) — systematic loser analysis needed")
    cat.gaps.append("No cross-year loser validation possible with current data")
    cat.observations.append("Loser knowledge is the primary knowledge gap for IIOS")
    return cat


def _cat3_dna_knowledge(ctx: KVAContext) -> CategoryResult:
    """Category 3 — DNA lifecycle, regime survival, contradictions."""
    cat = CategoryResult(3, "DNA Knowledge")
    _section("CATEGORY 3 — DNA KNOWLEDGE")

    edges = ctx.edges

    # Group edges by status
    by_status: Dict[str, List[Any]] = defaultdict(list)
    for e in edges:
        st = str(getattr(e, "status", "UNKNOWN"))
        by_status[st].append(e)

    # Q1: Which DNA survived all regimes?
    high_wf = [e for e in edges
               if hasattr(e, "wf_consistency") and _safe_float(e.wf_consistency) >= 0.8
               and hasattr(e, "oos_win_rate") and _safe_float(e.oos_win_rate) >= 0.60]
    if high_wf:
        top = sorted(high_wf, key=lambda e: _safe_float(e.oos_win_rate), reverse=True)[:5]
        desc_str = "; ".join(
            f"{e.edge_id}(wf={_safe_float(e.wf_consistency):.1f} oos={_safe_float(e.oos_win_rate):.2f})"
            for e in top
        )
        answer1 = (f"{len(high_wf)} edges have WF consistency ≥ 0.8 and OOS win rate ≥ 60%. "
                   f"Top regime-survivors: {desc_str[:200]}")
        conf1 = 0.75
    else:
        answer1 = f"No edges with both WF≥0.8 and OOS≥60% yet. {len(edges)} edges analysed."
        conf1 = 0.30

    a1 = KnowledgeAnswer(
        question="Which DNA survived all regimes?",
        answer=answer1,
        evidence=[f"{len(high_wf)} regime-robust edges"],
        supporting_studies=["study002", "re001a"],
        confidence=conf1,
        knowledge_source="KnowledgeProvider / edges",
        knowledge_confidence=conf1*80, evidence_strength=min(90, len(high_wf)*8),
        cross_year=70.0, cross_regime=75.0,
        explainability=85.0, completeness=60.0, novelty=60.0, consistency=70.0,
    )
    cat.questions.append(a1)
    _q(a1.question, a1.answer, a1.confidence)

    # Q2: Which DNA disappeared?
    decaying = by_status.get("DECAYING", by_status.get("<EdgeStatus.DECAYING: 'DECAYING'>", []))
    # also check string representation
    decaying = [e for e in edges if "DECAY" in str(getattr(e,"status","")).upper()]
    candidate= [e for e in edges if "CANDIDATE" in str(getattr(e,"status","")).upper()]

    answer2 = (f"{len(decaying)} edges are DECAYING (signals weakening), "
               f"{len(candidate)} edges are CANDIDATE (being evaluated). "
               f"DECAYING edges are DNA patterns that were valid but lost predictive power.")
    conf2 = 0.70

    a2 = KnowledgeAnswer(
        question="Which DNA disappeared / is decaying?",
        answer=answer2,
        evidence=[f"{len(decaying)} DECAYING edges, {len(candidate)} CANDIDATE"],
        supporting_studies=["re001a"],
        confidence=conf2,
        knowledge_source="KnowledgeProvider / edges (status=DECAYING)",
        knowledge_confidence=conf2*80, evidence_strength=min(90, len(decaying)/3),
        cross_year=65.0, cross_regime=60.0,
        explainability=90.0, completeness=70.0, novelty=55.0, consistency=75.0,
    )
    cat.questions.append(a2)
    _q(a2.question, a2.answer, a2.confidence)

    # Q3: Which DNA evolved?
    # IKN EVOLVED_TO relationships
    ikn_stats = ctx.ikn_stats
    evolved_rels = 0
    if ikn_stats:
        evolved_rels = ikn_stats.relationships_by_type.get("EVOLVED_TO", 0)
    answer3 = (f"IKN records {evolved_rels} EVOLVED_TO relationships. "
               f"Total DNA nodes in IKN: {ikn_stats.nodes_by_type.get('DNA', 0) if ikn_stats else 0}. "
               f"DNA evolution tracking is operational through IKN versioning.")
