def _cat6_feature_intelligence(ctx: KVAContext) -> CategoryResult:
    """Category 6 — Feature importance and predictive power."""
    cat = CategoryResult(6, "Feature Intelligence")
    _section("CATEGORY 6 — FEATURE INTELLIGENCE")

    features = ctx.features

    # Compute feature → forward_return correlations
    feature_cols: Dict[str, List[float]] = defaultdict(list)
    returns: List[float] = []

    for feat in features:
        fr = _safe_float(getattr(feat, "forward_return", float("nan")), float("nan"))
        if math.isnan(fr):
            continue
        fdict = getattr(feat, "features", {}) or {}
        if not fdict:
            continue
        returns.append(fr)
        for k, v in fdict.items():
            feature_cols[k].append(_safe_float(v))

    # Align lengths
    n = len(returns)
    feature_corrs: Dict[str, float] = {}
    for fname, vals in feature_cols.items():
        if len(vals) == n and n >= 10:
            feature_corrs[fname] = _corr(vals, returns)

    ranked_pos = sorted(((f, c) for f, c in feature_corrs.items() if c > 0),
                         key=lambda x: abs(x[1]), reverse=True)
    ranked_neg = sorted(((f, c) for f, c in feature_corrs.items() if c < 0),
                         key=lambda x: abs(x[1]), reverse=True)
    ranked_all = sorted(feature_corrs.items(), key=lambda x: abs(x[1]), reverse=True)

    if ranked_all:
        top5 = ", ".join(f"{f}(r={c:.3f})" for f, c in ranked_all[:5])
        low5 = ", ".join(f"{f}(r={c:.3f})" for f, c in ranked_all[-5:])
        answer1 = (f"Feature-return correlations computed on {n} samples. "
                   f"Most predictive: {top5}. "
                   f"Least predictive: {low5}.")
        conf1 = 0.75
