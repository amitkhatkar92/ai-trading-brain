def _gen_feature_intelligence(ctx: KVAContext) -> Path:
    cat = next((c for c in ctx.categories if c.category_id == 6), None)
    lines = [_md_header("KVA Feature Intelligence")]
    if cat:
        lines.append(f"**Category Score:** {cat.score:.1f}/100  \n")
        for q in cat.questions:
            lines.append(f"### {q.question}\n")
            lines.append(f"**Answer:** {q.answer}\n")
    # Feature correlation table from answers
    lines.append("## Feature-Return Correlations\n")
    features = ctx.features
    feature_cols: Dict[str, List[float]] = defaultdict(list)
    returns: List[float] = []
    for feat in features:
        fr = _safe_float(getattr(feat, "forward_return", float("nan")), float("nan"))
        if math.isnan(fr):
            continue
        fdict = getattr(feat, "features", {}) or {}
        if not fdict:
            continue
        returns.append(fr)
        for k, v in fdict.items():
            feature_cols[k].append(_safe_float(v))
    n = len(returns)
    feature_corrs: Dict[str, float] = {}
    for fname, vals in feature_cols.items():
        if len(vals) == n and n >= 10:
            feature_corrs[fname] = _corr(vals, returns)
    if feature_corrs:
        lines.append(f"(n={n} samples)\n")
        lines.append("| Feature | Correlation | |Direction| Predictive Power |")
        lines.append("|---------|-------------|---------|-----------------|")
        for fname, corr in sorted(feature_corrs.items(), key=lambda x: abs(x[1]), reverse=True):
            dir_str = "↑ positive" if corr > 0 else "↓ negative"
            power = "HIGH" if abs(corr) >= 0.15 else "MEDIUM" if abs(corr) >= 0.05 else "LOW"
            lines.append(f"| {fname} | {corr:.4f} | {dir_str} | **{power}** |")
    # Feature appearance in edge conditions
    lines.append("\n## Feature Appearance in Discovery Conditions\n")
    feat_edge_count: Dict[str, int] = Counter()
    for e in ctx.edges:
        raw = getattr(e, "raw", {}) or {}
        for cond in raw.get("entry_conditions", []):
            if isinstance(cond, dict):
                feat_edge_count[cond.get("feature", "?")] += 1
    if feat_edge_count:
        lines.append("| Feature | Edge Appearances |")
        lines.append("|---------|-----------------|")
        for f, cnt in feat_edge_count.most_common(20):
            lines.append(f"| {f} | {cnt} |")
    return _write("KVA_FEATURE_INTELLIGENCE.md", "\n".join(lines))


