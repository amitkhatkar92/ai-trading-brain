def _load_all(ctx: KVAContext) -> None:
    _section("LOADING KNOWLEDGE STORES")

    # KnowledgeProvider
    try:
        from autonomous_research.knowledge_provider import KnowledgeProvider
        kp = KnowledgeProvider()
        ctx.studies       = kp.list_studies()
        ctx.findings      = kp.list_findings()
        ctx.edges         = kp.list_edges()
        ctx.features      = kp.list_features()
        ctx.regime_history = kp.get_regime_history()
        ctx.replay_summary = kp.get_replay_summary()
        print(f"  ✔  KnowledgeProvider: {len(ctx.studies)} studies, "
              f"{len(ctx.findings)} findings, {len(ctx.edges)} edges, "
              f"{len(ctx.features)} features, {len(ctx.regime_history)} regime records")
    except Exception as e:
        print(f"  ✗  KnowledgeProvider: {e}")

    # Separate findings by type
    for f in ctx.findings:
        cls = str(getattr(f, "classification", ""))
        if "WINNER_DNA" in cls:
            ctx.winner_dna.append(f)
        elif "LOSER_DNA" in cls:
            ctx.loser_dna.append(f)
        elif "FEATURE_IMPORTANCE" in cls:
            ctx.feature_importance.append(f)
        elif "CLUSTER_PATTERN" in cls:
            ctx.cluster_patterns.append(f)

    print(f"  ✔  Findings parsed: {len(ctx.winner_dna)} winner DNA, "
          f"{len(ctx.loser_dna)} loser DNA, "
          f"{len(ctx.feature_importance)} feature importance, "
          f"{len(ctx.cluster_patterns)} cluster patterns")

    # IDR
    try:
        from market_learning.idr_repository import IDRRepository
        idr = IDRRepository()
        ctx.idr_stats = idr.statistics()
        print(f"  ✔  IDR: total_dna={ctx.idr_stats.total_dna}, "
              f"institutional={ctx.idr_stats.institutional_dna}, "
              f"avg_confidence={ctx.idr_stats.avg_confidence:.3f}")
    except Exception as e:
        print(f"  ⚠  IDR: {e}")

    # IKN
    try:
        from ikn.ikn_network import IKNNetwork
        ikn = IKNNetwork()
        ctx.ikn_stats = ikn.statistics()
        ikn.close()
        print(f"  ✔  IKN: {ctx.ikn_stats.total_nodes} nodes, "
              f"{ctx.ikn_stats.total_relationships} relationships, "
              f"avg_confidence={ctx.ikn_stats.avg_confidence:.3f}")
    except Exception as e:
        print(f"  ⚠  IKN: {e}")

    # HypothesisRegistry
    try:
        from autonomous_research.hypothesis_registry import HypothesisRegistry
        reg = HypothesisRegistry(knowledge_provider=None)
        ctx.hypotheses = reg.list_all()
        print(f"  ✔  HypothesisRegistry: {len(ctx.hypotheses)} hypotheses")
    except Exception as e:
        print(f"  ⚠  HypothesisRegistry: {e}")


