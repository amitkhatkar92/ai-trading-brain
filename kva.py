def _now() -> str:
    return datetime.now().isoformat(timespec="milliseconds")

def _section(title: str) -> None:
    print(f"\n{'═' * 72}\n  {title}\n{'═' * 72}")

def _q(q: str, a: str, conf: float = 0.0) -> None:
    icon = "✔" if conf >= 0.6 else ("⚠" if conf >= 0.3 else "?")
    print(f"  {icon}  Q: {q[:55]:<55}  conf={conf:.2f}")
    print(f"       A: {a[:100]}")

def _corr(xs: List[float], ys: List[float]) -> float:
    """Pearson correlation, returns 0 on error."""
    n = len(xs)
    if n < 5:
        return 0.0
    try:
        mx = sum(xs) / n;  my = sum(ys) / n
        cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
        sx  = math.sqrt(sum((x - mx) ** 2 for x in xs))
        sy  = math.sqrt(sum((y - my) ** 2 for y in ys))
        return cov / (sx * sy) if sx * sy > 0 else 0.0
    except Exception:
        return 0.0

def _percentile(values: List[float], p: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    k = (p / 100) * (len(s) - 1)
    lo, hi = int(k), min(int(k) + 1, len(s) - 1)
    return s[lo] + (k - lo) * (s[hi] - s[lo])

def _safe_float(v: Any, default: float = 0.0) -> float:
    try:
        return float(v)
    except (TypeError, ValueError):
        return default

def _write(filename: str, content: str) -> Path:
    p = REPORT_DIR / filename
    p.write_text(content, encoding="utf-8")
    return p

def _md_header(title: str) -> str:
    return (f"# {title}\n\n"
            f"**Issue:** {KVA_ISSUE}  \n"
            f"**Date:** {KVA_DATE}  \n"
            f"**Version:** {KVA_VERSION}  \n\n")

def _score_to_status(score: float) -> str:
    if score >= 75:
        return PASS
    if score >= 50:
        return WARN
    return FAIL


