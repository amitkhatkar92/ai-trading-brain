    _gap_analysis(ctx)

    # Phase 4: Scorecard
    _build_scorecard(ctx)

    # Phase 5: Final questions
    _final_questions(ctx)

    ctx.finish_time = _now()

    # Phase 6: Reports
    _section("GENERATING REPORTS")
