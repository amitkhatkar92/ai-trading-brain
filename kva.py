@dataclass
class KnowledgeAnswer:
    """A single assessed answer with evidence and score."""
    question:        str
    answer:          str
    evidence:        List[str]      = field(default_factory=list)
    supporting_studies: List[str]   = field(default_factory=list)
    supporting_years:   List[str]   = field(default_factory=list)
    supporting_regimes: List[str]   = field(default_factory=list)
    confidence:      float          = 0.0
    contradictions:  List[str]      = field(default_factory=list)
    knowledge_source: str           = ""
    # Scores 0-100
    knowledge_confidence: float = 0.0
    evidence_strength:    float = 0.0
    cross_year:           float = 0.0
    cross_regime:         float = 0.0
    explainability:       float = 0.0
    completeness:         float = 0.0
    novelty:              float = 0.0
    consistency:          float = 0.0

    @property
    def overall_score(self) -> float:
        return (self.knowledge_confidence + self.evidence_strength +
                self.cross_year + self.cross_regime +
                self.explainability + self.completeness +
                self.novelty + self.consistency) / 8.0

    @property
    def is_supported(self) -> bool:
        return bool(self.evidence) or bool(self.supporting_studies)


@dataclass
class CategoryResult:
    """Assessment result for one of the 10 knowledge categories."""
    category_id:  int
    category_name: str
    questions:    List[KnowledgeAnswer] = field(default_factory=list)
    score:        float = 0.0
    status:       str   = FAIL
    gaps:         List[str] = field(default_factory=list)
    observations: List[str] = field(default_factory=list)


