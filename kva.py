    regime_feature_avgs: Dict[str, Dict[str, float]] = defaultdict(dict)
    for feat in features:
        regime = str(getattr(feat, "regime", "?"))
        fdict  = getattr(feat, "features", {}) or {}
        for k, v in fdict.items():
            regime_feature_avgs[regime].setdefault(k, [])
            regime_feature_avgs[regime][k].append(_safe_float(v))
    regime_feature_means = {
        reg: {k: sum(v)/len(v) for k, v in feats.items()}
        for reg, feats in regime_feature_avgs.items()
    }
    # Compute cross-regime variance per feature
    if len(regime_feature_means) >= 2:
        regs = list(regime_feature_means.keys())
        feat_names = set(k for r in regs for k in regime_feature_means[r].keys())
        feat_stability: Dict[str, float] = {}
