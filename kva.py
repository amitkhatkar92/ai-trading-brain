def _build_scorecard(ctx: KVAContext) -> None:
    cat_scores = {c.category_id: c.score for c in ctx.categories}

    # Institutional Knowledge Score = average of winner + loser + DNA categories
    inst_cats = [cat_scores.get(1, 0), cat_scores.get(2, 0), cat_scores.get(3, 0)]
    sc = ctx.scorecard
    sc.institutional_score   = sum(inst_cats) / 3.0

    # DNA Quality
    edges = ctx.edges
    if edges:
        high_q = sum(1 for e in edges
                      if _safe_float(e.oos_win_rate) >= 0.65
                      and _safe_float(e.wf_consistency) >= 0.6)
        sc.dna_quality = min(100, high_q / len(edges) * 200)
    else:
        sc.dna_quality = 0.0

    # Scientific Confidence = C10 score + avg confidence of all answers
    all_answers = [a for c in ctx.categories for a in c.questions]
    avg_ans_conf = sum(a.confidence for a in all_answers) / max(len(all_answers), 1)
    sc.scientific_confidence = (cat_scores.get(10, 0) + avg_ans_conf * 100) / 2.0

    # Research Coverage = # studies / target(10) * 100
    sc.research_coverage = min(100, len(ctx.studies) / 10.0 * 100)

    # Completeness = avg of all category scores
    sc.completeness = sum(c.score for c in ctx.categories) / max(len(ctx.categories), 1)

    # Explainability = avg explainability of all answers
    sc.explainability = sum(a.explainability for a in all_answers) / max(len(all_answers), 1)

    # Reasoning Quality = C9 score
    sc.reasoning_quality = cat_scores.get(9, 0)

    # Overall rating
    sc.overall_rating = (
        sc.institutional_score * 0.20 +
        sc.dna_quality         * 0.20 +
        sc.scientific_confidence * 0.15 +
        sc.research_coverage   * 0.15 +
        sc.completeness        * 0.10 +
        sc.explainability      * 0.10 +
        sc.reasoning_quality   * 0.10
    )

    if sc.overall_rating >= 70:
        sc.certification = CERTIFIED
    elif sc.overall_rating >= 50:
        sc.certification = WARN
    else:
        sc.certification = FAIL

    import uuid
    sc.certificate_id = "KVA-" + uuid.uuid4().hex[:10].upper()

    _section("KNOWLEDGE SCORECARD")
    metrics = [
        ("Institutional Knowledge Score",  sc.institutional_score),
        ("DNA Quality Score",               sc.dna_quality),
        ("Scientific Confidence",           sc.scientific_confidence),
        ("Research Coverage",               sc.research_coverage),
        ("Knowledge Completeness",          sc.completeness),
        ("Knowledge Explainability",        sc.explainability),
        ("Reasoning Quality",               sc.reasoning_quality),
        ("Overall Rating",                  sc.overall_rating),
    ]
    for name, score in metrics:
        bar = "█" * int(score // 10)
        icon = "✔" if score >= 70 else "⚠" if score >= 50 else "✗"
        print(f"  {icon}  {name:<35s} {score:5.1f}  {bar}")
    print(f"\n  Certification: {sc.certification}")
    print(f"  Certificate:   {sc.certificate_id}")


