# ── ForecastPoint ─────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class ForecastPoint:
    """A single predicted value at a specific time offset."""

    step:           int     # 1..DEFAULT_FORECAST_POINTS
    offset_seconds: float   # seconds ahead of now
    value:          float
    lower_bound:    float
    upper_bound:    float
    confidence:     float   # [0, 1]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "step":           self.step,
            "offset_seconds": self.offset_seconds,
            "value":          self.value,
            "lower_bound":    self.lower_bound,
            "upper_bound":    self.upper_bound,
            "confidence":     self.confidence,
        }


# ── Forecast ──────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Forecast:
    """
    Immutable operational forecast for a single PredictionType.

    Generated by PredictiveForecaster.
    """

    forecast_id:       str
    prediction_type:   PredictionType
    domain:            PredictionDomain
    horizon:           ForecastHorizon
    forecast_points:   Tuple[ForecastPoint, ...]   = field(default_factory=tuple)
    trend:             TrendType                   = TrendType.UNKNOWN
    confidence:        float                       = 0.0
    horizon_seconds:   float                       = 0.0
    data_points_used:  int                         = 0
    algorithm:         str                         = "linear"
    generated_at:      float                       = field(default_factory=time.time)
    version:           str                         = VERSION

    @property
    def confidence_level(self) -> ConfidenceLevel:
        return confidence_to_level(self.confidence)

    @property
    def terminal_forecast(self) -> float:
        """Value at the end of the forecast horizon."""
        if not self.forecast_points:
            return 0.0
        return self.forecast_points[-1].value

    @property
    def point_count(self) -> int:
        return len(self.forecast_points)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "forecast_id":      self.forecast_id,
            "prediction_type":  self.prediction_type.value,
            "domain":           self.domain.value,
            "horizon":          self.horizon.value,
            "trend":            self.trend.value,
            "confidence":       self.confidence,
            "confidence_level": self.confidence_level.value,
            "terminal_forecast":self.terminal_forecast,
            "point_count":      self.point_count,
            "data_points_used": self.data_points_used,
            "algorithm":        self.algorithm,
            "generated_at":     self.generated_at,
        }


# ── ProbabilityReport ─────────────────────────────────────────────────────────

@dataclass(frozen=True)
class ProbabilityReport:
    """
    Immutable probability estimates for prediction types.
    """

    report_id:        str
    domain:           PredictionDomain
    horizon:          ForecastHorizon
    probabilities:    Dict[str, float]        = field(default_factory=dict, compare=False)
    confidence_scores: Dict[str, float]       = field(default_factory=dict, compare=False)
    generated_at:     float                   = field(default_factory=time.time)
    version:          str                     = VERSION

    def get(self, prediction_type: PredictionType) -> float:
        return self.probabilities.get(prediction_type.value, 0.0)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "report_id":        self.report_id,
            "domain":           self.domain.value,
            "horizon":          self.horizon.value,
            "probabilities":    dict(self.probabilities),
            "confidence_scores":dict(self.confidence_scores),
            "generated_at":     self.generated_at,
        }


