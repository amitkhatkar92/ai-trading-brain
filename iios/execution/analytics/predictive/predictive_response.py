# ── PredictiveSnapshot ────────────────────────────────────────────────────────

@dataclass(frozen=True)
class PredictiveSnapshot:
    """
    Immutable point-in-time snapshot of all active forecasts.
    """

    snapshot_id:  str
    domain:       PredictionDomain
    horizon:      ForecastHorizon
    forecasts:    Tuple[Forecast, ...]   = field(default_factory=tuple)
    captured_at:  float                  = field(default_factory=time.time)
    version:      str                    = VERSION

    @property
    def forecast_count(self) -> int:
        return len(self.forecasts)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "snapshot_id":    self.snapshot_id,
            "domain":         self.domain.value,
            "horizon":        self.horizon.value,
            "forecast_count": self.forecast_count,
            "captured_at":    self.captured_at,
            "version":        self.version,
        }


# ── PredictionReport ──────────────────────────────────────────────────────────

@dataclass(frozen=True)
class PredictionReport:
    """
    Immutable full prediction report — the primary output of the
    Predictive Intelligence Framework.

    Returned by PredictiveIntelligenceEngine.process().
    """

    report_id:            str
    request_id:           str
    domain:               PredictionDomain
    horizon:              ForecastHorizon
    forecasts:            Tuple[Forecast, ...]
    snapshot:             PredictiveSnapshot
    probability_report:   Optional[ProbabilityReport]   = None
    capacity_forecast:    Optional[CapacityForecast]    = None
    risk_forecast:        Optional[RiskForecast]        = None
    operational_forecast: Optional[OperationalForecast] = None
    forecast_summary:     Optional[ForecastSummary]     = None
    error_message:        str                           = ""
    processing_ms:        float                         = 0.0
    generated_at:         float                         = field(default_factory=time.time)
    version:              str                           = VERSION

    @property
    def is_success(self) -> bool:
        return not self.error_message

    @property
    def forecast_count(self) -> int:
        return len(self.forecasts)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "report_id":           self.report_id,
            "request_id":          self.request_id,
            "domain":              self.domain.value,
            "horizon":             self.horizon.value,
            "forecast_count":      self.forecast_count,
            "has_probabilities":   self.probability_report is not None,
            "has_capacity":        self.capacity_forecast is not None,
            "has_risk":            self.risk_forecast is not None,
            "has_operational":     self.operational_forecast is not None,
            "has_summary":         self.forecast_summary is not None,
            "error_message":       self.error_message,
            "processing_ms":       self.processing_ms,
            "generated_at":        self.generated_at,
            "version":             self.version,
        }


# ── Factory helpers ───────────────────────────────────────────────────────────

def make_predictive_snapshot(
    domain:    PredictionDomain,
    horizon:   ForecastHorizon,
    forecasts: List[Forecast],
    *,
    snapshot_id: Optional[str] = None,
) -> PredictiveSnapshot:
    return PredictiveSnapshot(
        snapshot_id = snapshot_id or str(uuid.uuid4()),
        domain      = domain,
        horizon     = horizon,
        forecasts   = tuple(forecasts),
    )
