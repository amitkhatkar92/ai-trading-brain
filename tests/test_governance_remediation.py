class TestG002DivergenceDetector(unittest.TestCase):

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()

    def test_gr008_divergence_creates_investigation(self):
        """GR-008: Material WR divergence (36pp) creates a RESEARCH_REQUIRED record."""
        det = _make_detector(self.tmpdir)
        created = det.check_divergence(
            strategy_name   = "Mean_Reversion",
            live_wr         = 0.22,
            live_n          = 9,
            live_avg_r      = -0.188,
            synthetic_wr    = 0.58,
            synthetic_avg_r = 0.00715,
        )
        self.assertTrue(created)
        pending = det.get_pending_investigations()
        self.assertEqual(len(pending), 1)
        self.assertEqual(pending[0].status, STATUS_RESEARCH_REQUIRED)
        self.assertGreater(pending[0].wr_divergence, 0.15)

    def test_gr009_no_duplicate_investigations(self):
        """GR-009: Second check_divergence for open investigation is a no-op."""
        det = _make_detector(self.tmpdir)
        det.check_divergence("Mean_Reversion", 0.22, 9, -0.188, 0.58, 0.007)
        created_again = det.check_divergence("Mean_Reversion", 0.22, 9, -0.188, 0.58, 0.007)
        self.assertFalse(created_again)
        self.assertEqual(len(det.get_pending_investigations()), 1)

    def test_gr009b_insufficient_sample_skips_divergence(self):
        """GR-009b: Below min_live_sample â†’ no investigation created."""
        det = _make_detector(self.tmpdir, min_live_sample=10)
        created = det.check_divergence("Mean_Reversion", 0.22, 5, -0.188, 0.58, 0.007)
        self.assertFalse(created)
        self.assertEqual(len(det.get_pending_investigations()), 0)

    def test_gr009c_no_divergence_below_threshold(self):
        """GR-009c: Small WR gap below 15pp threshold â†’ no investigation."""
        det = _make_detector(self.tmpdir, min_wr_divergence=0.15, min_expectancy_divergence=0.30)
        created = det.check_divergence("Mean_Reversion", 0.53, 15, 0.10, 0.58, 0.20)
        self.assertFalse(created)


