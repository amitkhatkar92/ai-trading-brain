def _make_shm(tmpdir: str) -> StrategyHealthMonitor:
    """Create a StrategyHealthMonitor backed by a temp directory."""
    import trade_monitoring.strategy_health_monitor as _shm_mod
    orig = _shm_mod.HEALTH_DB_PATH
    _shm_mod.HEALTH_DB_PATH = os.path.join(tmpdir, "strategy_health.json")
    try:
        shm = StrategyHealthMonitor()
    finally:
        _shm_mod.HEALTH_DB_PATH = orig
    # Bind instance to temp path for save/load
    shm._db_path = os.path.join(tmpdir, "strategy_health.json")
    # Monkey-patch save/load to use temp path
    import trade_monitoring.strategy_health_monitor as _m
    _orig_save = _m.StrategyHealthMonitor._save_db
    _orig_load = _m.StrategyHealthMonitor._load_db

    def _save(self_inner):
        try:
            with open(self_inner._db_path, "w", encoding="utf-8") as f:
                json.dump(
                    {k: v.to_dict() for k, v in self_inner._records.items()},
                    f, indent=2,
                )
        except Exception:
            pass

    def _load(self_inner):
        p = self_inner._db_path
        if not os.path.exists(p):
            return
        try:
            with open(p, "r", encoding="utf-8") as f:
                raw = json.load(f)
            for k, v in raw.items():
                self_inner._records[k] = StrategyHealthRecord.from_dict(v)
        except Exception:
            pass

    shm._save_db = lambda: _save(shm)
    shm._load_db = lambda: _load(shm)
    return shm


def _make_detector(tmpdir: str, **cfg_kwargs) -> PerformanceDivergenceDetector:
    """Create a PerformanceDivergenceDetector backed by a temp directory."""
    import trade_monitoring.performance_divergence_detector as _dd_mod
    orig = _dd_mod.INVESTIGATIONS_PATH
    _dd_mod.INVESTIGATIONS_PATH = os.path.join(tmpdir, "divergence.json")
    try:
        cfg = DivergenceConfig(**cfg_kwargs)
        det = PerformanceDivergenceDetector(config=cfg)
    finally:
        _dd_mod.INVESTIGATIONS_PATH = orig
    det._inv_path = os.path.join(tmpdir, "divergence.json")

    def _save_det(self_inner):
        try:
            with open(self_inner._inv_path, "w") as f:
                json.dump({k: v.to_dict() for k, v in self_inner._investigations.items()}, f)
        except Exception:
            pass

    det._save = lambda: _save_det(det)
    return det


