# â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•â•

class TestG001EarlyAbortDeadlock(unittest.TestCase):

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.shm = _make_shm(self.tmpdir)

    def _drive_to_early_abort(self):
        """Record 9 losing trades to trigger EARLY_ABORT."""
        for _ in range(9):
            self.shm.record_trade("Mean_Reversion", -0.02, -1.0)

    def test_gr001_strategy_enters_early_abort(self):
        """GR-001: After 9 losing trades, Mean_Reversion is DISABLED via EARLY_ABORT."""
        self._drive_to_early_abort()
        self.assertIn("Mean_Reversion", self.shm.get_disabled_strategies())
        rec = self.shm._records["Mean_Reversion"]
        self.assertEqual(rec.disabled_reason, DISABLE_REASON_EARLY_ABORT)

    def test_gr002_strategy_remains_disabled_during_cooldown(self):
        """GR-002: Strategy stays in disabled set during cooldown."""
        self._drive_to_early_abort()
        for _ in range(EARLY_ABORT_COOLDOWN - 1):
            self.shm.tick_session()
        self.assertIn("Mean_Reversion", self.shm.get_disabled_strategies())

    def test_gr003_cooldown_expiry_sets_revalidation_pending(self):
        """GR-003: After cooldown, revalidation_pending becomes True."""
        self._drive_to_early_abort()
        for _ in range(EARLY_ABORT_COOLDOWN):
            self.shm.tick_session()
        rec = self.shm._records["Mean_Reversion"]
        self.assertTrue(rec.revalidation_pending)
        self.assertIsNotNone(rec.revalidation_timestamp)

    def test_gr004_strategy_not_auto_enabled_after_cooldown(self):
        """GR-004: Strategy must NOT appear in passing set after cooldown expires."""
        self._drive_to_early_abort()
        for _ in range(EARLY_ABORT_COOLDOWN):
            self.shm.tick_session()
        self.assertIn("Mean_Reversion", self.shm.get_disabled_strategies(),
                      "Strategy must remain DISABLED after cooldown expiry")

    def test_gr005_failed_revalidation_keeps_strategy_disabled(self):
        """GR-005: mark_revalidation_complete(FAIL) leaves strategy disabled."""
        self._drive_to_early_abort()
        for _ in range(EARLY_ABORT_COOLDOWN):
            self.shm.tick_session()
        self.shm.mark_revalidation_complete("Mean_Reversion", "FAIL", "metrics still poor")
        rec = self.shm._records["Mean_Reversion"]
        self.assertEqual(rec.revalidation_result, "FAIL")
        self.assertFalse(rec.revalidation_pending)
        self.assertIn("Mean_Reversion", self.shm.get_disabled_strategies())

    def test_gr006_successful_revalidation_requires_normal_promotion(self):
        """GR-006: PASS result does NOT auto-enable strategy."""
        self._drive_to_early_abort()
        for _ in range(EARLY_ABORT_COOLDOWN):
            self.shm.tick_session()
        self.shm.mark_revalidation_complete("Mean_Reversion", "PASS", "sampling artifact")
        rec = self.shm._records["Mean_Reversion"]
        self.assertEqual(rec.revalidation_result, "PASS")
        self.assertFalse(rec.revalidation_pending)
        # Still disabled â€” PASS alone is not sufficient
        self.assertIn("Mean_Reversion", self.shm.get_disabled_strategies(),
                      "PASS result alone must not re-enable the strategy")

    def test_gr007_revalidation_is_idempotent(self):
        """GR-007: Extra tick_session calls do not create duplicate revalidation requests."""
        self._drive_to_early_abort()
        for _ in range(EARLY_ABORT_COOLDOWN):
            self.shm.tick_session()
        ts1 = self.shm._records["Mean_Reversion"].revalidation_timestamp
        # Extra ticks
        self.shm.tick_session()
        self.shm.tick_session()
        reval = self.shm.get_revalidation_required()
        self.assertIn("Mean_Reversion", reval)
        # Timestamp must not change after extra ticks
        self.assertEqual(self.shm._records["Mean_Reversion"].revalidation_timestamp, ts1)


