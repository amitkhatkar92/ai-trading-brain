# ─── G: actual_fill_price used for P&L ──────────────────────────────────────

class TestActualFillPriceForPnL(unittest.TestCase):
    def test_g_pnl_uses_actual_fill_price(self):
        """If actual_fill_price > 0, P&L uses it instead of signal entry_price."""
        # rec.entry_price = 2500 (signal), actual_fill_price = 2502 (slippage)
        # exit_price = 2600
        # expected pnl = (2600 - 2502) * qty   NOT (2600 - 2500) * qty
        rec = _make_order_record(entry_price=2500.0, quantity=10, direction="BUY")
        rec.actual_fill_price = 2502.0   # slipped by 2 pts

        _entry_for_pnl = rec.actual_fill_price if rec.actual_fill_price > 0 else rec.entry_price
        exit_price = 2600.0
        pnl = (exit_price - _entry_for_pnl) * rec.quantity

        self.assertAlmostEqual(pnl, 980.0, places=2,
                               msg="P&L must use actual fill price, not signal price")
        self.assertNotAlmostEqual(pnl, 1000.0, places=2,
                                  msg="P&L must NOT use the signal entry price")


