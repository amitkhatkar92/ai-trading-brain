def _fill_response(status: str, fill_price: float = 0.0, qty: int = 0, slip: float = 0.0):
    """Build a dict mimicking DhanFeed.get_fill_details() output."""
    return {
        "status": status,
        "actual_fill_price": fill_price,
        "filled_quantity": qty,
        "slippage_abs": slip,
        "slippage_pct": round(slip / fill_price * 100, 4) if fill_price > 0 else 0.0,
        "raw_status": "TRADED",
        "reconciliation_source": "DHAN_LIVE",
    }


