# ─── O: Anti-lookahead invariant ─────────────────────────────────────────────

class TestAntiLookahead(unittest.TestCase):
    def test_o_lol_no_lookahead_flag_in_schema(self):
        """LOL schema must NOT include an outcome_at earlier than decision_at."""
        # Structural: LOL has no_lookahead=True in obs dict; we test the invariant
        # by building a sample record and verifying decision_at < outcome_at.
        from learning_system.learning_observation_ledger import _empty_record
        from datetime import date
        rec = _empty_record(
            obs_id="OBS_OA",
            symbol="TCS",
            direction="BUY",
            trading_date=date.today().isoformat(),
            observed_at=datetime.now().isoformat(),
            entry_price=3500.0,
            stop_loss=3450.0,
            target_price=3600.0,
        )
        # decision_at and outcome_at must both be present and correctly ordered
        # when filled in. The schema just needs them as separate fields.
        self.assertIn("decision_at", rec)
        self.assertIn("outcome_at", rec)
        # Simulate a realistic record to verify ordering would be honoured
        now = datetime.now()
        decision_at_str = now.isoformat()
        outcome_at_str  = (now + timedelta(hours=6)).isoformat()
        self.assertLess(decision_at_str, outcome_at_str,
                        "decision_at must be before outcome_at (no lookahead)")

    def test_o_kda_no_lookahead_flag_true(self):
        """KDADecisionRecord must always have no_lookahead=True."""
        from knowledge_authority.kda_models import KDADecisionRecord
        import dataclasses
        for f in dataclasses.fields(KDADecisionRecord):
            if f.name == "no_lookahead":
                self.assertTrue(f.default, "no_lookahead must default to True")


