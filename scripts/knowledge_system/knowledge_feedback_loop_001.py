def _log_event(event: Dict) -> None:
    KNOWLEDGE_LEDGER.parent.mkdir(parents=True, exist_ok=True)
    with open(KNOWLEDGE_LEDGER, "a") as f:
        f.write(json.dumps(event) + "\n")


def _load_all_questions() -> List[ResearchQuestion]:
    if not RQ_QUEUE_PATH.exists():
        return []
    questions = []
    from scripts.knowledge_system.ksl_models import ResearchQuestionStatus
    with open(RQ_QUEUE_PATH) as f:
        for line in f:
            try:
                d = json.loads(line)
                rq = ResearchQuestion(
                    research_question_id=d["research_question_id"],
                    created_at=d.get("created_at", ""),
                    source_pattern_ids=d.get("source_pattern_ids", []),
                    question=d.get("question", ""),
                    problem_area=d.get("problem_area", "OTHER"),
                    direction=d.get("direction", "BOTH"),
                    regime_scope=d.get("regime_scope", "ALL"),
                    baseline=d.get("baseline", ""),
                    candidate_change=d.get("candidate_change", ""),
                    target_metric=d.get("target_metric", ""),
                    minimum_sample=d.get("minimum_sample", 100),
                    required_data=d.get("required_data", []),
                    known_data_gaps=d.get("known_data_gaps", []),
                    leakage_risk=d.get("leakage_risk", "LOW"),
                    research_priority=d.get("research_priority", 0.0),
                    status=ResearchQuestionStatus(d.get("status", "GENERATED")),
                    duplicate_of=d.get("duplicate_of"),
                    notes=d.get("notes", ""),
                )
                # Skip superseded
                from scripts.knowledge_system.ksl_models import ResearchArea
                try:
                    rq.problem_area = ResearchArea(d.get("problem_area", "OTHER"))
                except ValueError:
                    rq.problem_area = ResearchArea.OTHER
                if rq.status != ResearchQuestionStatus.SUPERSEDED:
                    questions.append(rq)
            except (KeyError, json.JSONDecodeError):
                pass
    return questions


def _save_state_json(summary: Dict, run_id: str, started_at: str,
                     patterns: List, questions: List, proposals: List) -> None:
    state = {
        "last_run_id": run_id,
        "last_run_at": started_at,
        "completed_at": summary.get("completed_at", ""),
        "total_evidence_records": summary.get("new_evidence_records", 0),
        "total_patterns_detected": len(patterns),
        "total_questions_in_queue": len(questions),
        "total_proposals_built": len(proposals),
        "safety": summary["safety"],
        "top_patterns": [
            {"type": p.pattern_type.value, "direction": p.direction,
             "strength": p.strength, "description": p.description}
            for p in patterns[:5]
        ],
    }
    tmp = STATE_JSON.with_suffix(".tmp")
    with open(tmp, "w") as f:
        json.dump(state, f, indent=2)
    os.replace(tmp, STATE_JSON)


def _save_research_queue_json(questions: List[ResearchQuestion]) -> None:
    queue = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "top_research_questions": [
            {
                "rank": i + 1,
                "research_question_id": q.research_question_id,
                "priority": q.research_priority,
                "area": q.problem_area.value,
                "direction": q.direction,
                "regime_scope": q.regime_scope,
                "question": q.question,
                "candidate_change": q.candidate_change,
                "target_metric": q.target_metric,
                "status": q.status.value,
            }
            for i, q in enumerate(questions)
        ],
    }
    RESEARCH_QUEUE_JSON.parent.mkdir(parents=True, exist_ok=True)
    tmp = RESEARCH_QUEUE_JSON.with_suffix(".tmp")
    with open(tmp, "w") as f:
        json.dump(queue, f, indent=2)
    os.replace(tmp, RESEARCH_QUEUE_JSON)


