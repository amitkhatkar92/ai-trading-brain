"""
scripts/knowledge_system/knowledge_feedback_loop_001.py
========================================================
Central orchestrator — Knowledge System Autonomous Research Loop KSL-001.

Runs all stages in sequence:
  1. INGEST          — consume new shadow records
  2. CLASSIFY        — evidence records classified (done inside consumer)
  3. DETECT PATTERNS — mine evidence ledger
  4. GENERATE RQs    — patterns → research questions
  5. PRIORITIZE      — score and rank questions
  6. BUILD PROPOSALS — proposals for top questions
  7. HYPOTHESIS INTEGRATION — register top questions in hypothesis_registry
  8. RECORD          — knowledge evidence ledger updated throughout
  9. STATE UPDATE    — save processing state

All writes are append-only.
Zero production mutations: no broker calls, no orders, no CandidateStore.
"""
