# ─── PipelineHealth ──────────────────────────────────────────────────────────

@dataclass
class PipelineHealth:
    """
    Health diagnostic snapshot for the AMLS pipeline.

    healthy=True means the pipeline ran successfully recently and all
    data stores are in consistent state.
    """
    healthy:              bool
    issues:               List[str]
    pipeline_state:       str         # PipelineState.value of last run (or WAITING)
    last_run_date:        Optional[str]
    last_success_date:    Optional[str]
    days_since_success:   Optional[int]
    missing_snapshot:     bool        # today's snapshot not found on disk
    missing_dna:          bool        # no DNA in ConsensusLibrary
    repository_ok:        bool        # IDR accessible
    gateway_ok:           bool        # PIG adapter loaded
    pipeline_interrupted: bool        # last run ended in RUNNING or PARTIAL state

    def to_dict(self) -> Dict[str, Any]:
        return {
            "healthy":              self.healthy,
            "issues":               self.issues,
            "pipeline_state":       self.pipeline_state,
            "last_run_date":        self.last_run_date,
            "last_success_date":    self.last_success_date,
            "days_since_success":   self.days_since_success,
            "missing_snapshot":     self.missing_snapshot,
            "missing_dna":          self.missing_dna,
            "repository_ok":        self.repository_ok,
            "gateway_ok":           self.gateway_ok,
            "pipeline_interrupted": self.pipeline_interrupted,
        }
